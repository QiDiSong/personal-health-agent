import { execFileSync } from 'node:child_process';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = new URL('../', import.meta.url);
const source = new URL('worker/index.js', root);
const archive = await build({ entryPoints: [fileURLToPath(new URL('worker/health-archive.js', root))], bundle: true, write: false, format: 'iife', globalName: 'HealthArchive', minify: true, platform: 'browser', target: 'es2022', legalComments: 'inline' });
const license = await readFile(new URL('node_modules/fflate/LICENSE', root), 'utf8');
const browserCode = '/* fflate 0.8.2\n' + license + '\n*/\n' + archive.outputFiles[0].text;
if (/<\/script/i.test(browserCode)) throw new Error('Unexpected closing script in browser archive bundle');
await writeFile(new URL('worker/archive-browser.js', root), '// Generated by scripts/build.mjs from the bounded local ZIP reader.\nexport const archiveBrowserJS = ' + JSON.stringify(browserCode) + ';\n');
const manifest = JSON.parse(await readFile(new URL('.openai/hosting.json', root), 'utf8'));
if (!manifest.project_id || manifest.static || manifest.d1 !== 'DB') {
  throw new Error('Expected the existing D1-backed Worker hosting configuration');
}
execFileSync(process.execPath, ['--check', fileURLToPath(source)], { stdio: 'inherit' });
const directory = new URL('dist/server/', root);
await mkdir(directory, { recursive: true });
await build({ entryPoints: [fileURLToPath(source)], outfile: fileURLToPath(new URL('index.js', directory)), bundle: true, format: 'esm', platform: 'browser', target: 'es2022', legalComments: 'none' });
console.log('Worker build ready: dist/server/index.js');
